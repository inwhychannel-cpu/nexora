const RTL_LANGS = ["ur", "ar"];

function nexoraApplyLang(lang) {
  if (!STRINGS[lang]) lang = "en";
  const dict = STRINGS[lang];
  document.querySelectorAll("[data-i18n]").forEach(function (el) {
    const key = el.getAttribute("data-i18n");
    if (dict[key]) el.textContent = dict[key];
  });
  document.documentElement.lang = lang;
  document.documentElement.dir = RTL_LANGS.indexOf(lang) >= 0 ? "rtl" : "ltr";
  try { localStorage.setItem("nexora-lang", lang); } catch (e) {}
  const sel = document.getElementById("lang-select");
  if (sel) sel.value = lang;
}

document.addEventListener("DOMContentLoaded", function () {
  let lang = "en";
  try { lang = localStorage.getItem("nexora-lang") || "en"; } catch (e) {}
  nexoraApplyLang(lang);
  const sel = document.getElementById("lang-select");
  if (sel) sel.addEventListener("change", function () { nexoraApplyLang(sel.value); });
});
